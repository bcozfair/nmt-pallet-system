-- ---------------------------------------------------------------------------
-- transactions.department_origin -- "มาจากไหน"
-- ---------------------------------------------------------------------------
--
-- กฎที่คอลัมน์นี้เก็บ:
--   เบิกออก   -- จาก "สถานที่ที่ทำรายการล่าสุด" ไปยัง สถานที่ที่เบิกไป
--   รับคืน    -- จาก "สถานที่ที่ทำรายการล่าสุด" ไปยัง Warehouse เสมอ
--   แจ้งชำรุด -- จาก "สถานที่ที่ทำรายการล่าสุด" (ไม่มีปลายทาง เพราะไม่ได้ย้ายของไปไหน)
--
-- "สถานที่ที่ทำรายการล่าสุด" คือ pallets.current_location ณ วินาทีก่อนบันทึกธุรกรรมนี้
-- ซึ่งมีค่าเท่ากับปลายทางของธุรกรรมก่อนหน้าของพาเลทใบเดียวกันเสมอ
--
-- ตารางเดิมเก็บแต่ปลายทาง (department_dest) ซึ่งตอบได้แค่ครึ่งเดียวของการเคลื่อนย้าย
-- หนึ่งครั้ง หน้าประวัติของพนักงานจึงบอกได้แค่ "เบิกออกไปยังคลังกลาง" แต่บอกไม่ได้ว่า
-- ของออกมาจากไหน และ "รับคืน" ยิ่งหนักกว่า -- แถวรับคืนเขียน department_dest เป็น
-- 'Warehouse' เสมอ ข้อมูลว่าของกลับมาจากที่ไหนไม่ได้ถูกเก็บไว้เลยแม้แต่ที่เดียว
--
-- ส่วนแถวแจ้งชำรุดเขียน department_dest เป็น null ตรง ๆ (การแจ้งชำรุดไม่ได้ย้ายของ
-- ไปไหน) จึงไม่มีอะไรในแถวนั้นบอกได้ว่าพาเลทชำรุดอยู่ที่จุดไหนตอนถูกแจ้ง
--
-- ข้อมูลนี้มีอยู่แล้วตอนเขียนแถว -- pallets.current_location คือคำตอบ แต่โค้ดเดิมอัปเดต
-- ทับมันทิ้งก่อนจะบันทึกธุรกรรม ค่าที่หายไปจึงไม่ใช่ค่าที่คำนวณย้อนหลังได้เสมอไป
-- (พาเลทที่คนอื่นเบิกไปอยู่นอกช่วงข้อมูลที่หน้านั้นโหลดมา) จึงต้องเก็บลงแถวตั้งแต่ต้นทาง
--
-- ต้องรันไฟล์นี้กับฐานข้อมูลก่อนอัปเดตโค้ดฝั่งแอป: โค้ดใหม่ insert คอลัมน์นี้ทุกครั้ง
-- ที่บันทึกธุรกรรม ถ้าคอลัมน์ยังไม่มี PostgREST จะปฏิเสธทั้งคำสั่ง = เบิก/คืน/แจ้งชำรุด
-- ไม่ได้ทั้งระบบ

alter table public.transactions
    add column if not exists department_origin text;

comment on column public.transactions.department_origin is
    'ที่ตั้งของพาเลทก่อนธุรกรรมนี้เกิดขึ้น (pallets.current_location ณ ขณะนั้น). '
    'null ได้เมื่อเป็นแถวเก่าก่อน migration นี้ หรือเมื่อไม่ทราบที่มาจริง ๆ';

-- ---- backfill แถวเก่า ------------------------------------------------------
--
-- เดาย้อนหลังจากปลายทางของธุรกรรมก่อนหน้าของพาเลทใบเดียวกัน ซึ่งเป็นข้อมูลที่ดีที่สุด
-- ที่ยังเหลืออยู่ -- ไม่ใช่ความจริงที่บันทึกไว้ตอนนั้น แต่เป็นข้อสรุปที่ตรงกับความจริง
-- ในทุกกรณีที่ประวัติของพาเลทไม่ขาดตอน
--
-- ข้ามแถวที่ department_dest เป็น null (แจ้งชำรุด/ตัดออก) ตอนมองหา "ปลายทางก่อนหน้า"
-- เพราะแถวพวกนั้นไม่ได้ย้ายของ การนับมันเป็นที่ตั้งจะทำให้ทุกแถวหลังการแจ้งชำรุดหนึ่ง
-- ครั้งกลายเป็น "ไม่ทราบที่มา" ทั้งที่พาเลทไม่ได้ขยับไปไหนเลย
--
-- แถวแรกสุดของแต่ละพาเลทไม่มีอะไรอยู่ก่อนหน้า จึงคงเป็น null ไว้ ไม่เดาว่าเป็นคลัง
-- ปล่อยให้หน้าจอแสดงว่า "ไม่ทราบที่มา" ตามความจริง ดีกว่าเติมค่าที่ดูน่าเชื่อลงไป
update public.transactions t
set department_origin = (
    select prev.department_dest
    from public.transactions prev
    where prev.pallet_id = t.pallet_id
      and prev.department_dest is not null
      and (prev.timestamp, prev.id) < (t.timestamp, t.id)
    order by prev.timestamp desc, prev.id desc
    limit 1
)
where t.department_origin is null;
